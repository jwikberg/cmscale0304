#!/usr/bin/env python3
"""Generate src/par_sites.h, which lists the instructions of cm0304.exe 4.1.5 that cmscale's parallel match
simulation (par_matches) redirects to per-thread storage.

- par_sites lists every instruction that addresses one of the scratch globals below with a plain 32-bit
  displacement, such as `mov ds:0xdc0118,eax` or `cmp ecx,DWORD PTR ds:0xdc011c`. For each one it gives the
  address, the length, the offset of the displacement within the instruction and which global it is.
- par_text_calls lists every `call rel32` in the match engine's code that calls into the text system. The
  functions in TEXT come from the engine's direct call graph and are the ones that can reach the string heaps'
  state. cmscale runs those calls under its string lock.

cmscale checks each site's bytes before patching. See docs/par-matches.md.

    python3 -I tools/par_sites.py EXE > src/par_sites.h
"""

import re
import subprocess
import sys

GLOBALS = [0xDC0118, 0xDC011C]  # the match engine's scratch globals, written ~15 million times a match
ENGINE = (0x8B0000, 0x972000)   # the match engine's code
TEXT = [0x972520, 0x6A7590, 0x97BF60, 0x97E020, 0x982830, 0x97EAC0, 0x9801F0, 0x4012B0, 0x97E1A0, 0x401290,
        0x97BDB0, 0x982FB0]     # text functions the engine calls directly


def main():
    exe = sys.argv[1]
    out = subprocess.run(["objdump", "-d", "-M", "intel", "--insn-width=16", exe],
                         capture_output=True, text=True, check=True).stdout
    sites, text_calls = [], []
    for line in out.splitlines():
        m = re.match(r"\s+([0-9a-f]+):\s+((?:[0-9a-f]{2} )+)\s*(.*)", line)
        if not m:
            continue
        code = bytes.fromhex(m.group(2).replace(" ", ""))
        addr = int(m.group(1), 16)
        if ENGINE[0] <= addr < ENGINE[1] and code[0] == 0xE8 and len(code) == 5:
            target = (addr + 5 + int.from_bytes(code[1:], "little", signed=True)) & 0xFFFFFFFF
            if target in TEXT:
                text_calls.append((addr, TEXT.index(target)))
        for k, g in enumerate(GLOBALS):
            pos = code.find(g.to_bytes(4, "little"))
            if pos < 0:
                continue
            if "ds:" not in m.group(3) or len(code) < 5:
                sys.exit(f"unexpected form at {m.group(1)}: {m.group(3)}")
            sites.append((int(m.group(1), 16), len(code), pos, k))
    print("/* Generated by tools/par_sites.py from cm0304.exe 4.1.5; do not edit. */")
    print(f"/* {len(sites)} instructions addressing " + ", ".join(f"{g:#x}" for g in GLOBALS) + " */")
    print("static const struct par_site { DWORD addr; BYTE len, disp, global; } par_sites[] = {")
    for i in range(0, len(sites), 4):
        print("    " + " ".join(f"{{{a:#x}, {n}, {p}, {k}}}," for a, n, p, k in sites[i:i + 4]))
    print("};")
    print()
    print(f"/* {len(text_calls)} calls from the match engine into the text system */")
    print("static const DWORD par_text_functions[] = {" + ", ".join(f"{t:#x}" for t in TEXT) + "};")
    print("static const struct par_text_call { DWORD addr; BYTE function; } par_text_calls[] = {")
    for i in range(0, len(text_calls), 6):
        print("    " + " ".join(f"{{{a:#x}, {k}}}," for a, k in text_calls[i:i + 6]))
    print("};")


if __name__ == "__main__":
    main()
