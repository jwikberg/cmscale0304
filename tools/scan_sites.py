#!/usr/bin/env python3
"""Generate src/scan_sites.h: the instructions of cm0304.exe 4.1.5 that cmscale's parallel candidate
scan (par_scan) redirects to per-thread storage.

Blocks of globals that the AI's candidate scans use as scratch (docs/par-scan.md):

- 0xd56128..0xd56147: context the evaluation functions (0x78de60..0x7907b0, 0x69b4c0, 0x6c1180) pass to
  each other, including a double at 0xd56138. Only plain memory operands address it.
- 0xd56740..0xd5674b: the one-entry date memo of 0x807260 and its family (the key, then an SI_SHORT_DATE
  object at 0xd56744). Besides memory operands, `mov ecx,imm32` and `push imm32` take its address.
- 0xd526e0..0xd52763: the player value function 0x60ab40's statics: an array of up to ten (int, int) pairs, six
  SI_SHORT_DATE objects from 0xd52730 (whose addresses it passes on) and their guard at 0xd52760.
- 0xd55f94: the pointer to the placeholder manager, which 0x75a410, 0x75a280 and 0x757930 point at a club and
  evaluate. Its ten loads become loads of the thread's own copy (a worker's points to its clone), falling back to
  the global when that is 0 (the game thread), since the game fills the global in when it loads a save.
- 0xeedc7c..0xeedc9f: the statics of the date functions 0x977150, 0x977410 and 0x977540 (the last two return
  the address of theirs).

Each site: its address, length, the offset of the 32-bit address within it, the kind (0 = memory operand,
1 = mov r32,imm32, 2 = push imm32, 3 = a load of the placeholder pointer), the block, the register (kinds 1
and 3) and the address it refers to. cmscale checks each site's bytes before patching. Every instruction in the
exe that refers into a block is listed, so the game thread and the workers each see only their own copy.

    python3 -I tools/scan_sites.py EXE > src/scan_sites.h
"""

import re
import subprocess
import sys

BLOCKS = [(0xD56128, 0xD56148), (0xD56740, 0xD5674C), (0xD526E0, 0xD52764), (0xD55F94, 0xD55F98), (0xEEDC7C, 0xEEDCA0)]
PLACEHOLDER = 3


def main():
    exe = sys.argv[1]
    out = subprocess.run(["objdump", "-d", "-M", "intel", "--insn-width=16", exe],
                         capture_output=True, text=True, check=True).stdout
    sites = []
    for line in out.splitlines():
        m = re.match(r"\s+([0-9a-f]+):\s+((?:[0-9a-f]{2} )+)\s*(.*)", line)
        if not m:
            continue
        addr, code, text = int(m.group(1), 16), bytes.fromhex(m.group(2).replace(" ", "")), m.group(3)
        for b, (lo, hi) in enumerate(BLOCKS):
            hits = [(pos, int.from_bytes(code[pos:pos + 4], "little")) for pos in range(len(code) - 3)
                    if lo <= int.from_bytes(code[pos:pos + 4], "little") < hi]
            if not hits:
                continue
            if len(hits) > 1:
                sys.exit(f"{addr:#x}: more than one reference: {text}")
            pos, target = hits[0]
            reg = 0
            memory = "ds:" in text or re.search(r"\[[^]]*0x%x\]" % target, text)
            if b == PLACEHOLDER:
                if code[0] == 0xA1 and len(code) == 5:
                    kind = 3
                elif code[0] == 0x8B and len(code) == 6 and code[1] & 0xC7 == 0x05:
                    kind, reg = 3, code[1] >> 3 & 7
                else:
                    sys.exit(f"{addr:#x}: unexpected form: {text}")
            elif memory:
                kind = 0
            elif 0xB8 <= code[0] <= 0xBF and len(code) == 5:
                kind, reg = 1, code[0] - 0xB8
            elif code[0] == 0x68 and len(code) == 5:
                kind = 2
            else:
                sys.exit(f"{addr:#x}: unexpected form: {text}")
            if len(code) < 5:
                sys.exit(f"{addr:#x}: too short to patch: {text}")
            sites.append((addr, len(code), pos, kind, b, reg, target))
    print("/* Generated by tools/scan_sites.py from cm0304.exe 4.1.5; do not edit. */")
    print("/* blocks: " + ", ".join(f"{lo:#x}..{hi - 1:#x}" for lo, hi in BLOCKS) + f"; {len(sites)} instructions */")
    print("static const DWORD scan_blocks[][2] = {" + ", ".join(f"{{{lo:#x}, {hi:#x}}}" for lo, hi in BLOCKS) + "};")
    print("static const struct scan_site { DWORD addr; BYTE len, pos, kind, block, reg; DWORD target; } scan_sites[] = {")
    for i in range(0, len(sites), 3):
        print("    " + " ".join(f"{{{a:#x}, {n}, {p}, {k}, {b}, {r}, {t:#x}}}," for a, n, p, k, b, r, t in sites[i:i + 3]))
    print("};")


if __name__ == "__main__":
    main()
