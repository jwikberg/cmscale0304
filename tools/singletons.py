#!/usr/bin/env python3
"""Generate src/singletons.h: the guarded singleton statics of cm0304.exe 4.1.5.

MSVC initialises a function-local static on first use behind a guard bit, and sets the bit before the value:

    test BYTE PTR ds:GUARD,BIT / jne done
    or   DWORD PTR ds:GUARD,BIT
    ... push ID
    call 0x983800                ; the game's singleton registry: the object with that id
    add  esp,4
    mov  ds:STATIC,eax
    done: ... use ds:STATIC

On one thread that's fine. When two threads run such code for the first time together, the second can find the bit
set and read the static while it is still 0 (cmscale's par_scan hit this, docs/par-scan.md). This
lists every such site: guard, bit, how the id is given (a byte global or a constant) and the static. cmscale fills
them in, as the game's own first call would, before it runs a scan on several threads.

    python3 -I tools/singletons.py EXE > src/singletons.h
"""

import re
import subprocess
import sys

REGISTRY = 0x983800
# guard, bit, id kind, id, static, call site: sites whose guard is set in another way. 0x61be70's function sets bit
# 0x100 of 0xd528dc with `mov ebp,ecx; or ebp,eax; mov ds:0xd528dc,ebp` (eax = 0x100), then looks up the byte id at
# 0xd0e30f into 0xd528b8.
EXTRA = [(0xD528DC, 0x100, 1, 0xD0E30F, 0xD528B8, 0x61BE70)]


def main():
    exe = sys.argv[1]
    out = subprocess.run(["objdump", "-d", "-M", "intel", exe], capture_output=True, text=True, check=True).stdout
    ins = []
    for line in out.splitlines():
        m = re.match(r"\s+([0-9a-f]+):\s+(?:[0-9a-f]{2} )+\s*(.*)", line)
        if m:
            ins.append((int(m.group(1), 16), m.group(2).strip()))
    sites, skipped = [], []
    for i, (addr, text) in enumerate(ins):
        if text != f"call   {REGISTRY:#x}":
            continue
        store = next((re.search(r"mov +ds:(0x[0-9a-f]+),eax", t) for a, t in ins[i + 1:i + 4]
                      if re.search(r"mov +ds:0x[0-9a-f]+,eax", t)), None)
        window = ins[max(0, i - 24):i]
        guard = [(j, re.search(r"or +DWORD PTR ds:(0x[0-9a-f]+),(\w+)", t)) for j, (a, t) in enumerate(window)]
        guard = [(j, m) for j, m in guard if m]
        if not store or not guard:
            continue
        j, g = guard[-1]
        regs = {}  # register -> ("const", value) or ("byte", address), from the window before the call
        bit = None
        for k, (a, t) in enumerate(window):
            if m := re.match(r"mov +(e[a-d]x|e[sd]i|ebp),(0x[0-9a-f]+)$", t):
                regs[m.group(1)] = ("const", int(m.group(2), 16))
            elif m := re.match(r"xor +(e[a-d]x|e[sd]i|ebp),\1$", t):
                regs[m.group(1)] = ("const", 0)
            elif m := re.match(r"mov +([a-d])l,(?:BYTE PTR )?ds:(0x[0-9a-f]+)$", t):
                regs["e" + m.group(1) + "x"] = ("byte", int(m.group(2), 16))
            elif m := re.match(r"movzx +(e[a-d]x),BYTE PTR ds:(0x[0-9a-f]+)$", t):
                regs[m.group(1)] = ("byte", int(m.group(2), 16))
            if k == j:  # the guard's bit: an immediate, or a register holding a constant here
                v = g.group(2)
                bit = int(v, 16) if v.startswith("0x") else regs.get(v, (None, None))[1] if regs.get(v, ("",))[0] == "const" else None
        push = next((t for a, t in reversed(window) if t.startswith("push")), "")
        if m := re.match(r"push +(0x[0-9a-f]+)$", push):
            id_kind, id_val = 0, int(m.group(1), 16)
        elif (m := re.match(r"push +(e[a-d]x)$", push)) and m.group(1) in regs:
            kind, v = regs[m.group(1)]
            id_kind, id_val = (0, v) if kind == "const" else (1, v)
        else:
            skipped.append(addr)
            continue
        if bit is None or bit & (bit - 1) or not bit:
            skipped.append(addr)
            continue
        sites.append((int(g.group(1), 16), bit, id_kind, id_val, int(store.group(1), 16), addr))
    known = {e[5] for e in EXTRA}
    sites += [e for e in EXTRA if e[5] in skipped]
    skipped = [a for a in skipped if a not in known]
    print("/* Generated by tools/singletons.py from cm0304.exe 4.1.5; do not edit. */")
    print(f"/* {len(sites)} guarded singleton statics; {len(skipped)} calls not understood: "
          + ", ".join(f"{a:#x}" for a in skipped) + " */")
    print("static const struct singleton { DWORD guard, bit; BYTE id_kind; DWORD id, value, site; } singletons[] = {")
    print("    /* id_kind 0: the id is the constant id; 1: the byte at address id */")
    for i in range(0, len(sites), 2):
        print("    " + " ".join(f"{{{g:#x}, {b:#x}, {k}, {v:#x}, {s:#x}, {a:#x}}}," for g, b, k, v, s, a in sites[i:i + 2]))
    print("};")


if __name__ == "__main__":
    main()
